def get_curated_fact_for_slot(target_date: date, target_hour: int, target_minute: int = 0) -> Dict[str, str]:
    min_slot = 1 if target_minute >= 30 else 0
    slot = target_hour * 2 + min_slot
    day_offset = target_date.toordinal() * 11
    index = (day_offset + slot) % len(CURATED_FACTS)
    return CURATED_FACTS[index]

def get_curated_fact_for_hour(target_date: date, target_hour: int) -> Dict[str, str]:
    return get_curated_fact_for_slot(target_date, target_hour, 0)

def get_curated_fact_for_date(target_date: date) -> Dict[str, str]:
    return get_curated_fact_for_slot(target_date, 0, 0)

