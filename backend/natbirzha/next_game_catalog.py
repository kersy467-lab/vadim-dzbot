def get_next_game_catalog() -> list[dict]:
    return [
        {
            "id": sector_id,
            "name": name,
            "icon": icon,
            "description": description,
            "branches": [
                {"id": branch_id, "name": branch_name, "outputs": outputs,
                 "future_choices": list(future_choices)}
                for branch_id, branch_name, outputs, future_choices in branches
            ],
        }
        for sector_id, name, icon, description, branches in CORPORATIONS
    ]


def find_next_game_sector(sector_id: str) -> dict | None:
    return next((item for item in get_next_game_catalog() if item["id"] == sector_id), None)


